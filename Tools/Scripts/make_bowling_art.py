"""Make the bowling alley's own art: the pin mesh and the living-room door sign.

Walt, 2026-09-27. The Retro Bowling Alley pack has a lane and a ball but no pins, and the
living-room door needs a "BOWLING" sign in the spirit of the poker machine's ace card.
Both are drawn here from numbers, not bought and not generated by AI, so nothing about
them needs a line in the Steam disclosure, and running this again rebuilds them exactly.

    python Tools/Scripts/make_bowling_art.py [out_dir]

Writes, into out_dir (default Tools/Art/Bowling):
    SM_BowlingPin.obj + .mtl   the pin, a lathe of the USBC profile, Y up, base at the
                               origin, centimetres; two materials, white body, red neck
                               stripes (the OBJ importer turns the .mtl colours into
                               materials)
    T_Sign_Bowling.png         the door sign, 1024 x 2048, transparent outside the card

The pin's numbers are the ones BowlingSim.h uses: 15 in tall, 4.766 in at the belly,
4.5 in up, which is where the ball meets it.
"""

import math
import os
import sys

IN = 2.54  # cm

# USBC pin profile: (height above the base, diameter), inches. The belly, neck and head
# are the regulation checkpoints; the points between follow the standard curve.
PROFILE_IN = [
    (0.000, 2.031), (0.375, 2.420), (0.750, 2.828), (1.500, 3.460), (2.250, 3.906),
    (3.375, 4.510), (4.500, 4.766), (5.875, 4.563), (7.250, 3.703), (8.000, 3.050),
    (8.625, 2.472), (9.375, 1.965), (10.000, 1.797), (10.875, 1.870), (11.750, 2.080),
    (12.625, 2.400), (13.500, 2.547), (14.000, 2.420), (14.450, 2.000), (14.750, 1.400),
    (14.930, 0.700), (15.000, 0.000),
]

# The two red neck stripes, as height bands in inches.
STRIPES_IN = [(9.55, 9.85), (10.15, 10.45)]


def profile_cm():
    """The profile resampled finely enough that the stripes fall on ring boundaries."""
    pts = [(h * IN, d * IN * 0.5) for h, d in PROFILE_IN]
    cuts = sorted({h * IN for band in STRIPES_IN for h in band})
    out = []
    for (h0, r0), (h1, r1) in zip(pts, pts[1:]):
        steps = max(2, int(math.ceil((h1 - h0) / 0.6)))
        for k in range(steps):
            t = k / steps
            out.append((h0 + (h1 - h0) * t, r0 + (r1 - r0) * t))
    out.append(pts[-1])
    for c in cuts:  # insert exact stripe edges
        for i in range(len(out) - 1):
            if out[i][0] < c < out[i + 1][0]:
                t = (c - out[i][0]) / (out[i + 1][0] - out[i][0])
                out.insert(i + 1, (c, out[i][1] + (out[i + 1][1] - out[i][1]) * t))
                break
    return out


def write_pin(out_dir, segments=48):
    prof = profile_cm()
    height = prof[-1][0]
    stripes = [(a * IN, b * IN) for a, b in STRIPES_IN]

    def in_stripe(h):
        return any(a - 1e-6 <= h <= b + 1e-6 for a, b in stripes)

    verts, norms, uvs = [], [], []
    # Profile normals: perpendicular to the silhouette, pointing out.
    ring_normals = []
    for i, (h, r) in enumerate(prof):
        h0, r0 = prof[max(i - 1, 0)]
        h1, r1 = prof[min(i + 1, len(prof) - 1)]
        dh, dr = h1 - h0, r1 - r0
        n_r, n_h = dh, -dr
        L = math.hypot(n_r, n_h) or 1.0
        ring_normals.append((n_r / L, n_h / L))
    for i, (h, r) in enumerate(prof):
        for s in range(segments + 1):
            a = 2 * math.pi * s / segments
            c, sn = math.cos(a), math.sin(a)
            verts.append((r * c, h, r * sn))          # Y up
            nr, nh = ring_normals[i]
            norms.append((nr * c, nh, nr * sn))
            uvs.append((s / segments, h / height))
    base_centre = len(verts)
    verts.append((0.0, 0.0, 0.0))
    norms.append((0.0, -1.0, 0.0))
    uvs.append((0.5, 0.0))

    white, red = [], []
    row = segments + 1
    for i in range(len(prof) - 1):
        mid = 0.5 * (prof[i][0] + prof[i + 1][0])
        target = red if in_stripe(mid) else white
        for s in range(segments):
            a = i * row + s
            b = a + 1
            c = a + row
            d = c + 1
            if prof[i + 1][1] > 1e-9:
                target.append((a, c, d, b))
            else:
                target.append((a, c, b))   # the tip closes to a point
    for s in range(segments):  # the flat base
        white.append((base_centre, s, s + 1))

    base = os.path.join(out_dir, "SM_BowlingPin")
    with open(base + ".mtl", "w", newline="\n") as f:
        f.write("# BowlingPin materials (Tools/Scripts/make_bowling_art.py)\n")
        f.write("newmtl M_PinWhite\nKd 0.93 0.92 0.90\nKs 0.6 0.6 0.6\nNs 180\n\n")
        f.write("newmtl M_PinRed\nKd 0.70 0.03 0.04\nKs 0.6 0.6 0.6\nNs 180\n")
    with open(base + ".obj", "w", newline="\n") as f:
        f.write("# Regulation bowling pin, 15 in (38.1 cm), Y up, base at origin, cm.\n")
        f.write("# Made by Tools/Scripts/make_bowling_art.py - do not edit by hand.\n")
        f.write("mtllib SM_BowlingPin.mtl\no SM_BowlingPin\n")
        for v in verts:
            f.write("v %.5f %.5f %.5f\n" % v)
        for t in uvs:
            f.write("vt %.5f %.5f\n" % t)
        for n in norms:
            f.write("vn %.5f %.5f %.5f\n" % n)
        for name, faces in (("M_PinWhite", white), ("M_PinRed", red)):
            f.write("usemtl %s\n" % name)
            for face in faces:
                f.write("f " + " ".join("%d/%d/%d" % (k + 1, k + 1, k + 1) for k in face) + "\n")
    return len(verts), len(white) + len(red), height


def write_sign(out_dir):
    from PIL import Image, ImageDraw, ImageFilter, ImageFont

    W, H = 1024, 2048
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))

    # The card: the alley's magenta neon on a deep night purple, rounded like a playing card.
    card = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(card)
    m, rad = 24, 90
    for y in range(m, H - m):
        t = (y - m) / (H - 2 * m)
        col = (int(40 + 30 * t), int(6 + 4 * t), int(62 + 20 * t), 255)
        d.line([(m, y), (W - m, y)], fill=col)
    mask = Image.new("L", (W, H), 0)
    ImageDraw.Draw(mask).rounded_rectangle([m, m, W - m, H - m], radius=rad, fill=255)
    img.paste(card, (0, 0), mask)

    # A neon border, with a glow.
    glow = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ImageDraw.Draw(glow).rounded_rectangle([m + 30, m + 30, W - m - 30, H - m - 30], radius=rad - 20,
                                           outline=(255, 60, 200, 255), width=22)
    img.alpha_composite(glow.filter(ImageFilter.GaussianBlur(18)))
    img.alpha_composite(glow)

    # The word.
    font = None
    for name in ("impact.ttf", "ariblk.ttf", "arialbd.ttf"):
        try:
            font = ImageFont.truetype(os.path.join(os.environ.get("WINDIR", "C:/Windows"), "Fonts", name), 190)
            break
        except OSError:
            continue
    font = font or ImageFont.load_default()
    word = "BOWLING"
    text = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    td = ImageDraw.Draw(text)
    box = td.textbbox((0, 0), word, font=font)
    tw, th = box[2] - box[0], box[3] - box[1]
    tx, ty = (W - tw) // 2 - box[0], 150 - box[1]
    td.text((tx, ty), word, font=font, fill=(255, 150, 230, 255))
    img.alpha_composite(text.filter(ImageFilter.GaussianBlur(14)))
    td2 = ImageDraw.Draw(img)
    td2.text((tx, ty), word, font=font, fill=(255, 255, 255, 255))

    # The pin, drawn from the same profile as the mesh, big, in the middle of the card,
    # shaded like a lit cylinder row by row so it reads as round.
    import numpy as np
    prof = profile_cm()
    pin_h = 1450.0
    scale = pin_h / (15.0 * IN)
    cx, base_y = W / 2, H - 170
    right = [(cx + r * scale, base_y - h * scale) for h, r in prof]
    left = [(cx - r * scale, base_y - h * scale) for h, r in reversed(prof)]
    outline = right + left
    pin_mask = Image.new("L", (W, H), 0)
    ImageDraw.Draw(pin_mask).polygon(outline, fill=255)

    hs = np.array([h for h, _ in prof]) * scale
    rs = np.array([r for _, r in prof]) * scale
    ys = np.arange(H, dtype=float)
    radius = np.interp(base_y - ys, hs, rs, left=0.0, right=0.0)[:, None]
    xs = (np.arange(W, dtype=float)[None, :] - cx) / np.maximum(radius, 1.0)
    nx = np.clip(xs, -1.0, 1.0)
    nz = np.sqrt(np.clip(1.0 - nx * nx, 0.0, 1.0))
    light = np.clip(0.35 + 0.65 * (nz * 0.8 - nx * 0.45), 0.0, 1.0)   # lit from the upper left
    shine = np.clip((nz * 0.8 - nx * 0.6) - 0.62, 0.0, 1.0) * 2.2       # a soft specular band
    body = np.stack([250 * light + 40 * shine, 248 * light + 40 * shine, 244 * light + 40 * shine], -1)
    height_in = (base_y - ys)[:, None] / scale / IN
    red = np.zeros_like(nx, dtype=bool)
    for a0, b0 in STRIPES_IN:
        red |= (height_in >= a0) & (height_in <= b0)
    body[red] = np.stack([205 * light + 30 * shine, 14 * light + 30 * shine, 26 * light + 30 * shine], -1)[red]
    body = np.clip(body, 0, 255).astype(np.uint8)
    pin = Image.fromarray(np.dstack([body, np.full((H, W), 255, np.uint8)]), "RGBA")

    halo = Image.new("RGBA", (W, H), (255, 80, 210, 0))
    halo.putalpha(pin_mask.filter(ImageFilter.GaussianBlur(28)))
    img.alpha_composite(halo)
    img.paste(pin, (0, 0), pin_mask)

    path = os.path.join(out_dir, "T_Sign_Bowling.png")
    img.save(path)
    return path


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "Art", "Bowling")
    os.makedirs(out, exist_ok=True)
    nv, nf, h = write_pin(out)
    print("pin: %d vertices, %d faces, %.2f cm tall" % (nv, nf, h))
    print("sign:", write_sign(out))
